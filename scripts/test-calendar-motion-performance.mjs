import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const marketing=readFileSync('marketing-experience-v5.js','utf8');
const calendar=readFileSync('experience-v4.js','utf8');
const css=readFileSync('calendar-dialog-polish.css','utf8');
assert.ok(!marketing.includes('offsetWidth'),'Marketing role changes must not force layout measurement');
assert.ok(marketing.includes("typeof preview.animate==='function'"),'Compositor motion feature detection');
assert.ok(marketing.includes('prefers-reduced-motion: reduce'),'Visitor motion preference respected');
assert.ok(marketing.includes('document.startViewTransition'),'Reuse native view transitions when present');
assert.ok(calendar.includes("month:'long',year:'numeric'"),'Full date with year announced');
assert.ok(calendar.includes("b.setAttribute('aria-pressed','false')"),'Day buttons start unselected');
assert.ok(calendar.includes("b.setAttribute('aria-pressed','true')"),'Selected day announced programmatically');
assert.ok(calendar.includes("lastOpenedFrom.focus({preventScroll:true})"),'Dialog returns focus to opening date');
assert.ok(calendar.includes("dialog.showModal()"),'Native modal interaction preferred');
assert.ok(calendar.includes("addEventListener('cancel'"),'Native Escape cancellation handled');
assert.ok(css.includes('::backdrop'),'Modal backdrop still present');
assert.ok(!/backdrop-filter:blur\(/.test(css),'Avoid costly page-wide blurred scrim');
assert.ok(css.includes('prefers-reduced-motion:reduce'),'Disable nonessential opening motion');
console.log('PASS — marketing role change avoids layout reflow; calendar date semantics, native dialog, focus restoration and reduced-motion safeguards retained.');
